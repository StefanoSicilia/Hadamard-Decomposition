%% Solution of Hadamard decomposition of a 4-by-4 A with A(1,2)=A(2,1)=0
% See script test_Grobner for more informations.

    %% X,U,Y and V such that A=(X*Y').*(U*V')
    [X1_1, X1_2,    1,    0, Y1_1, Y1_2,    1,    0]
    [X2_1, X2_2,    0,    1, Y2_1, Y2_2,    0,    1]
    [   1,    1, U3_1, U3_2,    1,    0, V3_1, V3_2]
    [   1,    1, U4_1, U4_2,    0,    1, V4_1, V4_2]
    
    %% Values of variables
    
    % X
    X1_1: (A1_3*(A3_2*A4_4 - A3_4*A4_2))/(A3_2*A4_3 - A3_3*A4_2)
    X2_1: (A2_3*(A3_1*A4_4 - A3_4*A4_1))/(A3_1*A4_3 - A3_3*A4_1)
    X1_2: A1_4
    X2_2: A2_4

    % U
    U3_1: -(A3_1*A3_2*A4_4 - A3_1*A3_4*A4_2)/(A3_1*A4_2 - A3_2*A4_1)
    U4_1: -(A3_2*A4_1*A4_4 - A3_4*A4_1*A4_2)/(A3_1*A4_2 - A3_2*A4_1)
    U3_2: (A3_1*A3_2*A4_4 - A3_2*A3_4*A4_1)/(A3_1*A4_2 - A3_2*A4_1)
    U4_2: (A3_1*A4_2*A4_4 - A3_4*A4_1*A4_2)/(A3_1*A4_2 - A3_2*A4_1)

    % V
    V3_1: (A3_2*A4_3 - A3_3*A4_2)/(A3_2*A4_4 - A3_4*A4_2)
    V4_1: 1
    V3_2: (A3_1*A4_3 - A3_3*A4_1)/(A3_1*A4_4 - A3_4*A4_1)
    V4_2: 1

    % Y
    Y1_1
    Num: (A3_2 A4_3 - A3_3 A4_2) (A1_1 A3_2 A4_4 - A1_1 A3_4 A4_2 + A1_4 A3_1 A4_2 - A1_4 A3_2 A4_1)
    Den: (A3_2 A4_4 - A3_4 A4_2) (A1_3 A3_2 A4_4 - A1_3 A3_4 A4_2 - A1_4 A3_2 A4_3 + A1_4 A3_3 A4_2)

    Y1_2
    Num: -(A1_1 A3_2 A4_3 - A1_1 A3_3 A4_2 + A1_3 A3_1 A4_2 - A1_3 A3_2 A4_1)
    Den: (A1_3 A3_2 A4_4 - A1_3 A3_4 A4_2 - A1_4 A3_2 A4_3 + A1_4 A3_3 A4_2)

    Y2_1
    Num: (A3_1 A4_3 - A3_3 A4_1) (A2_2 A3_1 A4_4 - A2_2 A3_4 A4_1 - A2_4 A3_1 A4_2 + A2_4 A3_2 A4_1)
    Den: (A3_1 A4_4 - A3_4 A4_1) (A2_3 A3_1 A4_4 - A2_3 A3_4 A4_1 - A2_4 A3_1 A4_3 + A2_4 A3_3 A4_1)

    Y2_2
    Num: -(A2_2 A3_1 A4_3 - A2_2 A3_3 A4_1 - A2_3 A3_1 A4_2 + A2_3 A3_2 A4_1)
    Den: (A2_3 A3_1 A4_4 - A2_3 A3_4 A4_1 - A2_4 A3_1 A4_3 + A2_4 A3_3 A4_1)
